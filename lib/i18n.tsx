export const DICT = { mn: MN, en: EN };

interface LanguageContextValue {
lang: Locale;
toggle: () => void;
t: (key: TranslationKey) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
// localStorage-тэй синхрончлогдсон хэл — useSyncExternalStore (SSR-аюулгүй)
const saved = useLocalStorageValue('mur-lang');
const lang: Locale = saved === 'en' || saved === 'mn' ? saved : 'mn';
useEffect(() => { document.documentElement.lang = lang; }, [lang]);

function toggle() {
setLocalStorageValue('mur-lang', lang === 'mn' ? 'en' : 'mn');
}

function t(key: TranslationKey): string {
return DICT[lang][key] || DICT.mn[key] || key;
}

return (
<LanguageContext.Provider value={{ lang, toggle, t }}>
{children}
</LanguageContext.Provider>
);
}

export function useLanguage() {
const ctx = useContext(LanguageContext);
if (!ctx) throw new Error('useLanguage нь LanguageProvider дотор ашиглагдах ёстой');
return ctx;
}
