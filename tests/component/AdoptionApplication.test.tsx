import { beforeEach, it, expect, vi } from 'vitest';
import { act, fireEvent, render, screen } from '@testing-library/react';
const m = vi.hoisted(() => ({ user: {id:'one'}, fetch:vi.fn(), create:vi.fn(), toast:vi.fn() }));
vi.mock('../../lib/useAuth',()=>({useAuth:()=>({user:m.user})}));
const translate = (key:string) => key;
vi.mock('../../lib/i18n',()=>({useLanguage:()=>({lang:'en',t:translate})}));
vi.mock('../../components/Toast',()=>({useToast:()=>m.toast}));
vi.mock('../../components/LoginModal',()=>({default:()=>null}));
vi.mock('../../lib/workflowService',()=>({fetchAdoptionApplications:m.fetch,createAdoptionApplication:m.create,updateAdoptionApplication:vi.fn()}));
import Panel from '../../components/AdoptionApplicationPanel';
beforeEach(()=>{m.user={id:'one'};m.fetch.mockReset().mockResolvedValue([]);m.create.mockReset();m.toast.mockReset();});
it('discards a previous account response',async()=>{
 let resolve!:(v:unknown[])=>void;
 m.fetch.mockImplementationOnce(()=>new Promise(r=>{resolve=r;}));
 const {rerender}=render(<Panel adoptionId="pet" ownerId="owner"/>);
 await act(async()=>{});
 m.user={id:'two'};rerender(<Panel adoptionId="pet" ownerId="owner"/>);
 await screen.findByLabelText('adoption_request_prompt');
 await act(async()=>resolve([{id:'old',message:'PRIVATE OLD DRAFT',status:'pending',createdAt:'2026-09-09'}]));
 expect(screen.queryByText('PRIVATE OLD DRAFT')).not.toBeInTheDocument();
});
it('locks pending text, prevents duplicate sends and keeps a failed draft',async()=>{
 let reject!:(e:Error)=>void;m.create.mockImplementation(()=>new Promise((_,r)=>{reject=r;}));
 render(<Panel adoptionId="pet" ownerId="owner"/>);
 const input=await screen.findByLabelText('adoption_request_prompt');
 fireEvent.change(input,{target:{value:'A long adoption request'}});
 const send=screen.getByRole('button',{name:'adoption_request_send'});
 fireEvent.click(send);fireEvent.click(send);
 expect(m.create).toHaveBeenCalledTimes(1);expect(input).toBeDisabled();
 await act(async()=>reject(new Error('offline')));
 expect(input).toHaveValue('A long adoption request');expect(input).toBeEnabled();
});
it('does not notify after account changes during send',async()=>{
 let resolve!:()=>void;m.create.mockImplementation(()=>new Promise<void>(r=>{resolve=r;}));
 const {rerender}=render(<Panel adoptionId="pet" ownerId="owner"/>);
 fireEvent.change(await screen.findByLabelText('adoption_request_prompt'),{target:{value:'A long adoption request'}});
 fireEvent.click(screen.getByRole('button',{name:'adoption_request_send'}));
 m.user={id:'two'};rerender(<Panel adoptionId="pet" ownerId="owner"/>);
 await screen.findByLabelText('adoption_request_prompt');await act(async()=>resolve());
 expect(m.toast).not.toHaveBeenCalled();
});
